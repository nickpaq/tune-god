import fs from 'node:fs';
import path from 'node:path';
import { stripTypeScriptTypes } from 'node:module';
const root = path.resolve(import.meta.dirname, '../..');
const here = import.meta.dirname;
const read = (file) => fs.readFileSync(path.join(root, file), 'utf8');
const js = (source) => stripTypeScriptTypes(source.replace(/^import .*;\s*$/gm, '')).replace(/\bexport /g, '');
const classify = read('src/audio/classify.ts');
const fft = js(classify.slice(classify.indexOf('export function fft'), classify.indexOf('export interface Features')));
const method = (file, name) => `const ${name} = (() => {\n${js(read(file))}\nreturn analyzeSong;\n})();`;
const helperDir = path.join(here, 'vendor/web-audio-beat-detector/src/helpers');
const helpers = fs.readdirSync(helperDir).filter((f) => f.endsWith('.ts')).map((f) => js(fs.readFileSync(path.join(helperDir, f), 'utf8'))).join('\n');
const licenses = '\n/* Music Tempo\n'+fs.readFileSync(path.join(here,'vendor/music-tempo-LICENSE'),'utf8')+'\nWeb Audio Beat Detector\n'+fs.readFileSync(path.join(here,'vendor/web-audio-beat-detector/LICENSE'),'utf8')+'\n*/\n';
const worker = [licenses, fft, method('src/audio/song/beats.ts', 'original'), method('experiments/auto-chopper/beatsExperimental.ts', 'corrected'), js(read('src/audio/song/driftFix.ts')), helpers, fs.readFileSync(path.join(here,'vendor/music-tempo.js'),'utf8'), fs.readFileSync(path.join(here,'worker.js'),'utf8')].join('\n');
fs.writeFileSync(path.join(here,'detectors.worker.js'),worker);
const template = fs.readFileSync(path.join(here,'index.template.html'),'utf8');
const app = fs.readFileSync(path.join(here,'lab.js'),'utf8');
const licensedTemplate = template.replace('</main>', '<details><summary>License texts</summary><pre style=\"white-space:pre-wrap;font-size:11px\">'+(licenses+'\n'+read('LICENSE')).replaceAll('&','&amp;').replaceAll('<','&lt;')+'</pre></details></main>');
const html = licensedTemplate.replace('WORKER_SOURCE_JSON', JSON.stringify(worker).replaceAll('<','\\u003c')).replace('APP_SOURCE', app.replaceAll('</script','<\\/script'));
fs.mkdirSync(path.join(root,'public/auto-chopper-lab'),{recursive:true});
fs.writeFileSync(path.join(root,'public/auto-chopper-lab/index.html'),html);
fs.writeFileSync(path.join(here,'auto-chopper-lab.html'),html);
console.log('Built self-contained comparison page ('+Buffer.byteLength(html)+' bytes).');
